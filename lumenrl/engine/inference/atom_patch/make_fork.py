#!/usr/bin/env python3
"""Generate aligned_paged_attention.py from the pinned aiter Triton MHA kernel source.

Only the K/V tile loads (and the extra paging arguments that feed them) change; every other
line of _attn_fwd_inner / _attn_fwd is copied verbatim. Asserts each edit applies exactly once.
The output keeps the source file's SPDX and AMD copyright lines.

Usage: make_fork.py <aiter>/aiter/ops/triton/_triton_kernels/attention/mha.py aligned_paged_attention.py
"""

import hashlib
import sys
from pathlib import Path

SRC_SHA = "33d539ae509b6dafec171f8e7aa0a15cb0d02f084b21405ab0a0faa109d74504"
API_SHA = "43f59ffa64a7ed43477c10b61e76ac5a6943b0279ee542471484b4a7edfad60b"


def block(text, start, end):
    i = text.index(start)
    j = text.index(end, i)
    return text[i:j]


def once(text, old, new):
    if text.count(old) != 1:
        raise SystemExit(f"edit anchor count {text.count(old)} != 1: {old[:70]!r}")
    return text.replace(old, new, 1)


def main(src_path, out_path):
    raw = Path(src_path).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == SRC_SHA, "pinned kernel source sha mismatch"
    src = raw.decode()
    notice = "".join(src.splitlines(keepends=True)[:2])
    if not (notice.startswith("# SPDX-License-Identifier: MIT\n") and "\n# Copyright (C) " in notice):
        raise SystemExit("pinned kernel source no longer starts with its SPDX/copyright lines")
    inner = block(src, "@triton.jit\ndef _attn_fwd_inner(", "_attn_fwd_repr = make_kernel_repr(")
    outer = block(src, "@triton.jit(repr=_attn_fwd_repr)\ndef _attn_fwd(", "@functools.lru_cache(maxsize=1024)\ndef _get_config(")

    inner = once(inner, "def _attn_fwd_inner(", "def _paged_attn_fwd_inner(")
    inner = once(inner, "    SLIDING_WINDOW: tl.constexpr,\n):\n    RCP_LN2",
                 "    SLIDING_WINDOW: tl.constexpr,\n    kc_ptr,\n    vc_ptr,\n    table_row_ptr,\n    row_real,\n"
                 "    kh,\n    PAGE: tl.constexpr,\n):\n    RCP_LN2")
    inner = once(inner, "        k = _load_fn(k_ptrs, k_offs_k, k_offs_n, BLOCK_DMODEL, seqlen_k)\n",
                 "        k = _paged_load_k(kc_ptr, table_row_ptr, row_real, kh, start_n, k_offs_n, seqlen_k,\n"
                 "                          BLOCK_N, BLOCK_DMODEL, PAGE)\n")
    v_old = "v = _load_fn(v_ptrs, k_offs_n, k_offs_k, seqlen_k, BLOCK_DMODEL)\n"
    if inner.count(v_old) != 2:
        raise SystemExit("expected two V loads (PRELOAD_V and late)")
    inner = inner.replace(v_old, "v = _paged_load_v(vc_ptr, table_row_ptr, row_real, kh, start_n, k_offs_n, seqlen_k,\n"
                                 "                              BLOCK_N, BLOCK_DMODEL, PAGE)\n")

    outer = once(outer, "@triton.jit(repr=_attn_fwd_repr)\ndef _attn_fwd(", "@triton.jit\ndef _paged_attn_fwd(")
    outer = once(outer, "    HEAD_STRIDE_ALIGNED_8: tl.constexpr = False,\n):",
                 "    HEAD_STRIDE_ALIGNED_8: tl.constexpr = False,\n    kc_ptr=None,\n    vc_ptr=None,\n"
                 "    table_ptr=None,\n    table_stride=0,\n    valid_ptr=None,\n    PAGE: tl.constexpr = 16,\n):")
    outer = once(outer, "    grp_sz: tl.constexpr = NUM_Q_HEADS // NUM_K_HEADS\n",
                 "    table_row_ptr = table_ptr + off_z.to(tl.int64) * table_stride\n"
                 "    row_real = tl.load(valid_ptr + off_z) != 0\n"
                 "    grp_sz: tl.constexpr = NUM_Q_HEADS // NUM_K_HEADS\n")
    if outer.count("acc, l_i, m_i = _attn_fwd_inner(") != 2:
        raise SystemExit("expected two inner calls")
    outer = outer.replace("acc, l_i, m_i = _attn_fwd_inner(", "acc, l_i, m_i = _paged_attn_fwd_inner(")
    tail = ("            SLIDING_WINDOW=SLIDING_WINDOW,\n"
            "            kc_ptr=kc_ptr,\n            vc_ptr=vc_ptr,\n            table_row_ptr=table_row_ptr,\n"
            "            row_real=row_real,\n            kh=off_k_head,\n            PAGE=PAGE,\n        )\n")
    if outer.count("            SLIDING_WINDOW=SLIDING_WINDOW,\n        )\n") != 2:
        raise SystemExit("expected two inner-call tails")
    outer = outer.replace("            SLIDING_WINDOW=SLIDING_WINDOW,\n        )\n", tail)

