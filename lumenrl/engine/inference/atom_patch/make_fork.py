@triton.jit
def _paged_load_k(kc_ptr, table_row_ptr, row_real, kh, start_n, k_offs_n, seqlen_k,
                  BLOCK_N: tl.constexpr, BLOCK_DMODEL: tl.constexpr, PAGE: tl.constexpr):
    # K^T tile [BLOCK_DMODEL, BLOCK_N] from K cache [pages, 8, D/8, PAGE, 8]; masked like _load_fn.
    tok = start_n + tl.arange(0, BLOCK_N)
    d = tl.arange(0, BLOCK_DMODEL)
    if k_offs_n is not None:
        live = (tok < seqlen_k) & row_real
        phy = tl.load(table_row_ptr + tok // PAGE, mask=live, other=0).to(tl.int64)
    else:
        phy = tl.load(table_row_ptr + tok // PAGE).to(tl.int64)
    pos = (tok % PAGE).to(tl.int64)
    off = (phy[None, :] * (8 * (BLOCK_DMODEL // 8) * PAGE * 8) + kh * ((BLOCK_DMODEL // 8) * PAGE * 8)
           + (d[:, None] // 8).to(tl.int64) * (PAGE * 8) + pos[None, :] * 8 + (d[:, None] % 8).to(tl.int64))
    if k_offs_n is not None:
        return tl.load(kc_ptr + off, mask=live[None, :], other=0.0)
    return tl.load(kc_ptr + off)


